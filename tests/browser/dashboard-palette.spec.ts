import {test,expect} from '@playwright/test'
import {mkdir,writeFile} from 'node:fs/promises'

test('dashboard landing palette preview',async({page})=>{
  await mkdir('artifacts/dashboard-palette',{recursive:true})
  await page.setViewportSize({width:1600,height:1000})
  await page.goto('/preview/dashboard-palette')
  await expect(page.getByRole('heading',{name:'Selamat siang, Pak Arief'}).or(page.getByRole('heading',{name:'Selamat pagi, Pak Arief'})).or(page.getByRole('heading',{name:'Selamat malam, Pak Arief'}))).toBeVisible()
  await page.evaluate(()=>document.fonts.ready)
  await expect(page.locator('main')).toContainText('Rp712.000')
  const palette=await page.locator('main').evaluate(el=>({background:getComputedStyle(el).backgroundColor,text:getComputedStyle(el).color,font:getComputedStyle(el).fontFamily}))
  expect(palette.background).toBe('rgb(28, 34, 46)')
  expect(palette.text).toBe('rgb(255, 255, 255)')
  expect(palette.font).toContain('Urbanist')
  const primary=await page.getByRole('button',{name:'Buka kasir',exact:true}).evaluate(el=>getComputedStyle(el).backgroundColor)
  expect(primary).toBe('rgb(24, 53, 217)')
  const bars=page.locator('.rounded-t-lg')
  await expect(bars).toHaveCount(7)
  for(const bar of await bars.all())expect((await bar.boundingBox())!.height).toBeGreaterThan(0)
  await page.screenshot({path:'artifacts/dashboard-palette/desktop.png',fullPage:true,animations:'disabled'})
  await page.getByRole('button',{name:'Menu akun',exact:true}).click()
  await expect(page.getByRole('button',{name:'Akun saya',exact:true})).toBeVisible()
  await page.screenshot({path:'artifacts/dashboard-palette/account-menu.png',animations:'disabled'})
  await page.getByRole('button',{name:'Menu akun',exact:true}).click()
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'artifacts/dashboard-palette/mobile.png',fullPage:true,animations:'disabled'})
  await page.getByRole('button',{name:'Buka navigasi',exact:true}).click()
  await expect(page.locator('main').getByRole('button',{name:'Produk',exact:true}).last()).toBeVisible()
  await page.screenshot({path:'artifacts/dashboard-palette/mobile-navigation.png',animations:'disabled'})
  await writeFile('artifacts/dashboard-palette/results.json',JSON.stringify({passed:true,palette,primary,chartBars:7,mobileOverflow:false,accountMenu:true,mobileNavigation:true,usesSampleData:true},null,2))
})
